export function translate(
  language: Language,
  key: string,
  params: Record<string, string | number> = {},
): string {
  const template = messages[language][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function statusLabel(language: Language, value: string | null | undefined): string {
  const normalized = value || "unknown";
  const key = `status.${normalized}`;
  const translated = translate(language, key);
  return translated === key ? normalized : translated;
}

function rawDetail(error: unknown): unknown {
  if (error && typeof error === "object" && "detail" in error) {
    return (error as { detail: unknown }).detail;
  }
  if (error instanceof Error) return error.message;
  return error;
}

export function translateErrorDetail(language: Language, error: unknown): string {
  const detail = rawDetail(error);
  if (detail && typeof detail === "object" && "code" in detail) {
    const data = detail as Record<string, unknown>;
    if (data.code === "quota_exceeded") {
      return translate(language, "error.quotaExceeded", {
        scope: String(data.scope_id ?? data.scope_type ?? ""),
        resource: String(data.resource ?? "quota"),
      });
    }
    if (data.code === "quota_output_limit_required") {
      return translate(language, "error.quotaOutputLimitRequired", {
        scope: String(data.scope_id ?? data.scope_type ?? ""),
      });
    }
    if (data.code === "quota_cost_projection_unavailable") {
      return translate(language, "error.quotaCostProjectionUnavailable", {
        scope: String(data.scope_id ?? data.scope_type ?? ""),
      });
    }
  }
  const text = typeof detail === "string" ? detail : String(detail ?? "");
  const lower = text.toLowerCase();
  const rules: Array<[string, string]> = [
    ["provider not found", "error.providerNotFound"],
    ["route not found", "error.routeNotFound"],
    ["persistence is not configured", "error.persistence"],
    ["secret storage is not configured", "error.secretStorage"],
    ["credential must be a non-empty string", "error.credentialRequired"],
    ["provider fields are required", "error.providerFields"],
    ["provider must exist before", "error.providerExists"],
    ["provider model discovery is not supported", "error.discoveryUnsupported"],
    ["provider has model routes", "error.providerHasRoutes"],
    ["provider id cannot be changed", "error.providerIdImmutable"],
    ["catalog source unavailable", "error.catalogUnavailable"],
    ["base_url must be", "error.baseUrl"],
    ["official_url must be", "error.publicUrl"],
    ["must be an https url", "error.publicUrl"],
    ["protocol must be", "error.protocol"],
    ["catalog_status must be draft or published", "error.catalogStatus"],
    ["route already exists", "error.routeExists"],
    ["models must be a non-empty list", "error.modelsRequired"],
  ];
  const matched = rules.find(([needle]) => lower.includes(needle));
  if (matched) return translate(language, matched[1]);
  if (!text) return translate(language, "error.generic", { message: "unknown" });
  return text;
}

type I18nValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: Translate;
  status: (value: string | null | undefined) => string;
  errorText: (error: unknown) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function initialLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "zh" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    locale: language === "zh" ? "zh-CN" : "en-US",
    setLanguage,
    t: (key, params) => translate(language, key, params),
    status: (status) => statusLabel(language, status),
    errorText: (error) => translateErrorDetail(language, error),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
